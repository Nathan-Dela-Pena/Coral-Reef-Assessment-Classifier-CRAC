"""Generate a small synthetic reef image set so the pipeline runs end to end.

    python scripts/make_demo_images.py --per-class 120

This is scaffolding, not science. The images are procedural textures with the
colour statistics each class actually has underwater -- living coral is brown-
gold with colour variance, bleached coral is near-white and low-variance, dead
rubble is grey, algae-covered is green. A CNN learns them easily, which is the
point: it proves the training loop, the export, the API and the dashboard all
work before you have real survey data.

Numbers produced from these images mean nothing about real reefs. Retrain on a
real labelled source (CoralNet, MLC, NCRMP) before reporting any result.
"""

import argparse
import random
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

from crac.model.dataset import LABELS

SIZE = 256

# (base RGB, per-pixel colour jitter, branch colour) per class.
PALETTE = {
    "healthy":       ((150, 95, 55), 38, (205, 140, 70)),
    "bleached":      ((238, 236, 230), 10, (252, 251, 248)),
    "dead":          ((122, 120, 116), 16, (96, 94, 92)),
    "algae_covered": ((70, 110, 55), 30, (105, 145, 60)),
}


def _texture(rng, base, jitter):
    """Fine grain plus smoothed low-frequency blotches.

    The coarse layer is blurred before it is added: a raw block repeat reads as a
    checkerboard, which is a texture no reef has.
    """
    noise = rng.normal(0, jitter, (SIZE, SIZE, 3))
    blocks = rng.normal(0, jitter * 1.6, (16, 16, 3)).repeat(16, 0).repeat(16, 1)
    coarse = np.array(
        Image.fromarray(np.clip(blocks + 128, 0, 255).astype("uint8"))
        .filter(ImageFilter.GaussianBlur(14)),
        dtype=float,
    ) - 128
    arr = np.array(base, dtype=float) + noise + coarse
    img = Image.fromarray(np.clip(arr, 0, 255).astype("uint8"))
    return img.filter(ImageFilter.GaussianBlur(1.1))


def _branches(img, rng, colour, n=26):
    draw = ImageDraw.Draw(img)
    for _ in range(n):
        x, y = rng.integers(0, SIZE, 2)
        for _ in range(rng.integers(3, 8)):
            dx, dy = rng.integers(-26, 26, 2)
            shade = tuple(int(np.clip(c + rng.normal(0, 18), 0, 255)) for c in colour)
            draw.line([(x, y), (x + dx, y + dy)], fill=shade, width=int(rng.integers(2, 6)))
            x, y = x + dx, y + dy
    return img


def make_image(label, rng):
    base, jitter, branch = PALETTE[label]
    img = _texture(rng, base, jitter)
    img = _branches(img, rng, branch)
    # Every underwater photo loses red with depth; apply it to all classes alike
    # so the model cannot use the cast itself as a shortcut.
    arr = np.array(img, dtype=float)
    arr[..., 0] *= rng.uniform(0.80, 0.95)
    arr[..., 2] *= rng.uniform(1.00, 1.14)
    img = Image.fromarray(np.clip(arr, 0, 255).astype("uint8"))
    return img.filter(ImageFilter.GaussianBlur(rng.uniform(0, 0.6)))


def main(argv=None):
    from crac.ingest.pipeline import load_sites

    p = argparse.ArgumentParser(description="Generate synthetic reef images for a demo run.")
    p.add_argument("--per-class", type=int, default=120)
    p.add_argument("--out", type=Path, default=Path("data/raw/images"))
    p.add_argument("--seed", type=int, default=0)
    args = p.parse_args(argv)

    args.out.mkdir(parents=True, exist_ok=True)
    # A marker the training code looks for, so a model fitted to these textures
    # is flagged as such everywhere its metrics are shown.
    (args.out / "SYNTHETIC_DEMO_DATA").write_text(
        "Images in this tree are procedurally generated by scripts/make_demo_images.py.\n"
        "Any accuracy measured on them describes synthetic textures, not coral.\n")

    rng = np.random.default_rng(args.seed)
    pyrng = random.Random(args.seed)
    sites = [s["id"] for s in load_sites()]
    years = list(range(2016, 2026))

    for label in LABELS:
        d = args.out / label
        d.mkdir(parents=True, exist_ok=True)
        for i in range(args.per_class):
            site = pyrng.choice(sites)
            # Weight the date so bleached/dead frames cluster in later years --
            # gives the Phase 3 trajectory something with a shape to it.
            bias = 0.0 if label == "healthy" else 0.35
            year = years[min(len(years) - 1,
                             int(pyrng.triangular(0, len(years) - 1,
                                                  (len(years) - 1) * (0.5 + bias))))]
            date = f"{year}-{pyrng.randint(1, 12):02d}-{pyrng.randint(1, 28):02d}"
            make_image(label, rng).save(d / f"site={site}_{date}_{i:04d}.jpg", quality=88)
        print(f"  {label:<14} {args.per_class} images -> {d}")

    print(f"\nwrote {args.per_class * len(LABELS)} synthetic images to {args.out}")
    print("Next: python scripts/build_manifest.py", args.out,
          "-o data/processed/manifest.csv")
    return 0


if __name__ == "__main__":
    sys.exit(main())
